def render_report(report: dict[str, Any], org: dict[str, Any], battery: dict[str, Any]) -> bytes:
    st = _styles()
    tz = org.get("timezone")
    _d = lambda v: _fmt_date(v, tz)  # noqa: E731
    buf = io.BytesIO()
    approved = report["status"] in ("approved", "superseded")
    label = f"{report['report_number']} v{report['version']}"
    doc = _doc(buf, f"Diagnostic report {label}")
    E: list[Any] = []
    evidence = report["evidence"]
    by_type: dict[str, list[dict]] = {}
    for item in evidence:
        by_type.setdefault(item["type"], []).append(item)

    E.append(Paragraph("Battery Diagnostic Report", st["h1"]))
    status_txt = {
        "approved": "<font color='#047857'><b>APPROVED</b></font>",
        "superseded": "<font color='#71717a'><b>SUPERSEDED BY A LATER VERSION</b></font>",
    }.get(report["status"], "<font color='#b45309'><b>DRAFT — NOT APPROVED</b></font>")
    E.append(Paragraph(f"{clean(report['title'])}<br/>{clean(label)} · {status_txt}", st["base"]))
    E.append(Spacer(1, 6))

    bat = (by_type.get("battery_record") or [{}])[0]
    bd = bat.get("data", {})
    src = bd.get("value_sources", {})
    rows = [[Paragraph("<b>Field</b>", st["cell"]), Paragraph("<b>Value</b>", st["cell"]), Paragraph("<b>Source of value</b>", st["cell"])]]
    for key, name, unit in [
        ("battery_id", "BatteryOS ID", None),
        ("customer", "Customer / supplier", None),
        ("received_date", "Received", None),
        ("battery_type", "Type", None),
        ("chemistry", "Chemistry", None),
        ("nominal_voltage_v", "Nominal voltage", "V"),
        ("rated_capacity_ah", "Rated capacity", "Ah"),
        ("pack_configuration", "Pack configuration", None),
        ("manufacturer", "Manufacturer", None),
        ("model", "Model", None),
        ("serial_number", "Serial number", None),
        ("bms_info", "BMS", None),
    ]:
        v = bd.get(key)
        if key == "received_date":
            shown = _d(v)
        elif key == "battery_type":
            shown = BATTERY_TYPE_LABELS.get(v, str(v))
        else:
            shown = _num(v, unit) if v not in (None, "unknown") else "Unknown"
        rows.append(
            [
                Paragraph(clean(name), st["cell"]),
                Paragraph(clean(shown.replace("_", " ")), st["cell"]),
                Paragraph(clean(SOURCE_TEXT.get(src.get(key), "Entered in BatteryOS") if key in src else "Entered in BatteryOS"), st["small"]),
            ]
        )
    E.append(Paragraph("Battery identification" + (f"  <font size=7 color='#71717a'>[{bat.get('key')}]</font>" if bat else ""), st["h2"]))
    E.append(_table(rows, [45 * mm, 70 * mm, 59 * mm]))
    if bd.get("intake_condition"):
        E.append(Spacer(1, 4))
        E.append(Paragraph(f"<b>Condition at intake (user-entered):</b> {clean(bd['intake_condition'])}", st["cell"]))

    E.append(Paragraph("How values are labelled", st["h2"]))
    legend = (
        "<b>Measured</b> — recorded from a test session with its conditions. <b>User-entered</b> — typed in by staff. "
        "<b>Calculated</b> — computed by BatteryOS from an imported file, with the method stated. "
        "<b>External</b> — a result from another lab or document. <b>Model estimate</b> — from a named, validated model. "
        "<b>Narrative</b> sections state whether they were AI-drafted, template-generated or written by the reviewer. "
        "References such as [M1] point to the evidence index at the end."
    )
    E.append(Paragraph(legend, st["small"]))

    sessions = {t["key"]: t for t in by_type.get("test_session", [])}
    if by_type.get("measurement"):
        E.append(Paragraph("Recorded results", st["h2"]))
        rows = [[Paragraph(f"<b>{h}</b>", st["cell"]) for h in ("Ref", "Quantity", "Value", "Type", "Conditions / source")]]
        for m in by_type["measurement"]:
            d = m["data"]
            value = _num(d.get("value"), d.get("unit")) if d.get("value") is not None else (d.get("value_text") or "—")
            cond = " ".join(
                x for x in [d.get("conditions"), f"Source: {d['source']}" if d.get("source") else None,
                            f"Test session [{d['test_session']}]" if d.get("test_session") else None] if x
            ) or "Conditions not recorded"
            rows.append(
                [
                    Paragraph(m["key"], st["small"]),
                    Paragraph(clean(d.get("quantity")), st["cell"]),
                    Paragraph(f"<b>{clean(value)}</b>", st["cell"]),
                    Paragraph(clean(KIND_LABELS.get(d.get("kind"), d.get("kind"))), st["cell"]),
                    Paragraph(clean(cond), st["small"]),
                ]
            )
        E.append(_table(rows, [11 * mm, 40 * mm, 28 * mm, 30 * mm, 65 * mm]))

    if sessions:
        E.append(Paragraph("Test sessions", st["h2"]))
        rows = [[Paragraph(f"<b>{h}</b>", st["cell"]) for h in ("Ref", "Test", "Date", "Equipment / operator", "Conditions")]]
        for key, t in sessions.items():
            d = t["data"]
            cond = "; ".join(
                x for x in [
                    f"ambient {_num(d['ambient_temp_c'], '°C')}" if d.get("ambient_temp_c") is not None else None,
                    f"charge {_num(d['charge_current_a'], 'A')}" if d.get("charge_current_a") is not None else None,
                    f"discharge {_num(d['discharge_current_a'], 'A')}" if d.get("discharge_current_a") is not None else None,
                    f"charge to {_num(d['charge_voltage_v'], 'V')}" if d.get("charge_voltage_v") is not None else None,
                    f"cut-off {_num(d['cutoff_voltage_v'], 'V')}" if d.get("cutoff_voltage_v") is not None else None,
                    d.get("method"),
                ] if x
            ) or "Not recorded"
            rows.append(
                [
                    Paragraph(key, st["small"]),
                    Paragraph(clean(d.get("test_type", "").replace("_", " ").capitalize()), st["cell"]),
                    Paragraph(_d(d.get("test_date")), st["cell"]),
                    Paragraph(clean(" · ".join(x for x in [d.get("equipment"), d.get("operator")] if x) or "—"), st["cell"]),
                    Paragraph(clean(cond), st["small"]),
                ]
            )
        E.append(_table(rows, [11 * mm, 32 * mm, 22 * mm, 45 * mm, 64 * mm]))

    for ds in by_type.get("dataset", []):
        d = ds["data"]
        E.append(Paragraph(f"Calculated from imported data [{ds['key']}]", st["h2"]))
        E.append(
            Paragraph(
                f"File <b>{clean(d['file'])}</b> · {d['imported_rows']:,} rows · SHA-256 {clean(d['file_sha256'][:16])}… · "
                "original file retained unchanged.",
                st["small"],
            )
        )
        rows = [[Paragraph(f"<b>{h}</b>", st["cell"]) for h in ("Metric", "Value", "Method")]]
        for x in d.get("calculated_metrics", []):
            rows.append(
                [
                    Paragraph(clean(x["metric"]), st["cell"]),
                    Paragraph(f"<b>{clean(_num(x['value'], x['unit']))}</b>", st["cell"]),
                    Paragraph(clean(x["method"]), st["small"]),
                ]
            )
        if len(rows) > 1:
            E.append(Spacer(1, 3))
            E.append(_table(rows, [55 * mm, 30 * mm, 89 * mm]))
        warns = [f for f in d.get("validation_findings", []) if f["severity"] in ("warning", "error")]
        if warns:
            E.append(Spacer(1, 3))
            E.append(Paragraph("<b>Data validation warnings acknowledged at import:</b>", st["cell"]))
            for w in warns:
                E.append(Paragraph(f"• {clean(w['message'])}", st["small"]))

    for n in by_type.get("note", []):
        d = n["data"]
        if not d.get("inspection_checklist"):
            continue
        E.append(Paragraph(f"Inspection checklist [{n['key']}] — technician observation", st["h2"]))
        rows = [[Paragraph(f"<b>{h}</b>", st["cell"]) for h in ("Item", "Result", "Comment")]]
        for c in d["inspection_checklist"]:
            res = {"ok": "No issue seen", "issue": "<font color='#b45309'><b>Issue noted</b></font>", "not_checked": "Not checked"}[c["result"]]
            rows.append([Paragraph(clean(c["item"]), st["cell"]), Paragraph(res, st["cell"]), Paragraph(clean(c.get("comment") or ""), st["small"])])
        E.append(_table(rows, [60 * mm, 30 * mm, 84 * mm]))
        E.append(Paragraph(f"Recorded by {clean(d.get('author'))} on {_d(d.get('written_on'))}.", st["small"]))

    for s in report["sections"]:
        if not s.get("paragraphs"):
            continue
        block = [
            Paragraph(clean(s["title"]), st["h2"]),
            Paragraph(clean(ORIGIN_TEXT.get(s.get("origin"), s.get("origin"))), st["origin"]),
            Spacer(1, 2),
        ]
        E.append(KeepTogether(block[:2]))
        for p in s["paragraphs"]:
            refs = f" <font size=7 color='#71717a'>[{', '.join(p['citations'])}]</font>" if p.get("citations") else ""
            E.append(Paragraph(clean(p["text"]) + refs, st["base"]))
            E.append(Spacer(1, 3))

    E.append(Paragraph("Reviewer conclusion", st["h2"]))
    E.append(Paragraph("Written by the qualified reviewer", st["origin"]))
    E.append(Paragraph(clean(report.get("reviewer_conclusion") or "Not yet written.").replace("\n", "<br/>"), st["base"]))
    E.append(Spacer(1, 8))
    if approved and report.get("approved_by"):
        E.append(
            Paragraph(
                f"<b>Approved by</b> {clean(report['approved_by']['full_name'])} on {_d(report.get('approved_at'))}.",
                st["base"],
            )
        )
    else:
        E.append(Paragraph("<font color='#b45309'><b>Not approved.</b></font> This is a draft for internal review.", st["base"]))

    E.append(Paragraph("Evidence index", st["h2"]))
    rows = [[Paragraph(f"<b>{h}</b>", st["cell"]) for h in ("Ref", "Record", "Information type")]]
    origin_text = {**KIND_LABELS, "technician": "Technician observation", "system": "System check"}
    for item in evidence:
        rows.append(
            [
                Paragraph(item["key"], st["small"]),
                Paragraph(clean(item["label"]), st["cell"]),
                Paragraph(clean(origin_text.get(item["origin"], item["origin"])), st["cell"]),
            ]
        )
    E.append(_table(rows, [12 * mm, 112 * mm, 50 * mm]))
    E.append(Spacer(1, 10))
    E.append(Paragraph(clean(DISCLAIMER), st["small"]))

    decorate = _page_decorator(org.get("name", ""), label, None if approved else "DRAFT - NOT APPROVED", tz)
    doc.build(E, onFirstPage=decorate, onLaterPages=decorate)
    return buf.getvalue()


