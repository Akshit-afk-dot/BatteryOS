def inr(paise: int) -> str:
    """Indian digit grouping: 1,23,45,678.90"""
    neg = paise < 0
    paise = abs(int(paise))
    rupees, p = divmod(paise, 100)
    s = str(rupees)
    if len(s) > 3:
        head, tail = s[:-3], s[-3:]
        groups = []
        while len(head) > 2:
            groups.insert(0, head[-2:])
            head = head[:-2]
        if head:
            groups.insert(0, head)
        s = ",".join(groups) + "," + tail
    return f"{'-' if neg else ''}{s}.{p:02d}"


def render_quotation(q: dict[str, Any], org: dict[str, Any], battery: dict[str, Any], customer: dict[str, Any] | None, report_number: str | None) -> bytes:
    st = _styles()
    tz = org.get("timezone")
    _d = lambda v: _fmt_date(v, tz)  # noqa: E731
    buf = io.BytesIO()
    approved = q["status"] in ("approved", "sent", "accepted")
    label = f"{q['number']} rev {q['revision']}"
    doc = _doc(buf, f"Quotation {label}")
    E: list[Any] = []

    org_lines = "<br/>".join(
        clean(x) for x in [org.get("legal_name") or org.get("name"), org.get("address"), org.get("phone"), org.get("email"),
                           f"GSTIN / Tax ID: {org['tax_id']}" if org.get("tax_id") else None] if x
    )
    status = {
        "approved": "Approved", "sent": "Sent", "accepted": "Accepted by customer", "declined": "Declined",
        "void": "Void", "draft": "Draft — not valid until approved",
    }[q["status"]]
    meta = (
        f"<b>Quotation {clean(q['number'])}</b> · revision {q['revision']}<br/>"
        f"Issue date: {_d(q.get('issue_date') or q.get('approved_at') or q.get('created_at'))}<br/>"
        f"Valid until: {_d(q.get('valid_until'))}<br/>Status: {clean(status)}"
    )
    head = Table(
        [[Paragraph(org_lines.replace("\n", "<br/>"), st["base"]), Paragraph(meta, st["right"])]],
        colWidths=[100 * mm, 74 * mm],
    )
    head.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("LEFTPADDING", (0, 0), (-1, -1), 0)]))
    E.append(Paragraph("Quotation", st["h1"]))
    E.append(head)
    E.append(Spacer(1, 8))

    cust = "<br/>".join(
        clean(x) for x in [customer.get("name"), customer.get("contact_name"), customer.get("address"), customer.get("phone"),
                           customer.get("email"), f"GSTIN / Tax ID: {customer['tax_id']}" if customer.get("tax_id") else None] if x
    ) if customer else "Customer not specified"
    ref_bits = [
        f"BatteryOS ID: {battery['bos_id']}",
        " ".join(x for x in [battery.get("manufacturer"), battery.get("model")] if x) or None,
        f"Serial: {battery['serial_number']}" if battery.get("serial_number") else None,
        " · ".join(
            x for x in [
                battery.get("chemistry") if battery.get("chemistry") not in (None, "unknown") else None,
                f"{battery['nominal_voltage_v']:g} V" if battery.get("nominal_voltage_v") else None,
                f"{battery['rated_capacity_ah']:g} Ah" if battery.get("rated_capacity_ah") else None,
            ] if x
        ) or None,
        f"Diagnostic report: {report_number}" if report_number else None,
    ]
    box = Table(
        [[Paragraph("<font size=7 color='#71717a'>QUOTATION FOR</font><br/>" + cust.replace("\n", "<br/>"), st["base"]),
          Paragraph("<font size=7 color='#71717a'>BATTERY</font><br/>" + "<br/>".join(clean(x) for x in ref_bits if x), st["base"])]],
        colWidths=[87 * mm, 87 * mm],
    )
    box.setStyle(TableStyle([("BOX", (0, 0), (-1, -1), 0.5, LINE), ("INNERGRID", (0, 0), (-1, -1), 0.5, LINE),
                             ("VALIGN", (0, 0), (-1, -1), "TOP"), ("TOPPADDING", (0, 0), (-1, -1), 6),
                             ("BOTTOMPADDING", (0, 0), (-1, -1), 6), ("LEFTPADDING", (0, 0), (-1, -1), 6)]))
    E.append(box)
    E.append(Spacer(1, 10))

    rows = [[Paragraph(f"<b>{h}</b>", st["cell"]) for h in ("#", "Description", "Qty", "Rate (INR)", "GST", "Amount (INR)")]]
    for i, line in enumerate(q["lines"], start=1):
        rows.append(
            [
                Paragraph(str(i), st["cell"]),
                Paragraph(clean(line["description"]), st["cell"]),
                Paragraph(f"{line['quantity']:g} {clean(line['unit'])}", st["cell"]),
                Paragraph(inr(line["unit_price_paise"]), st["right"]),
                Paragraph(f"{line['tax_rate_bp'] / 100:g}%", st["right"]),
                Paragraph(inr(line["line_subtotal_paise"]), st["right"]),
            ]
        )
    if len(rows) == 1:
        rows.append([Paragraph("", st["cell"]), Paragraph("No items", st["cell"]), "", "", "", ""])
    E.append(_table(rows, [8 * mm, 78 * mm, 20 * mm, 24 * mm, 14 * mm, 30 * mm]))
    E.append(Spacer(1, 4))
    totals = Table(
        [
            ["Subtotal", inr(q["subtotal_paise"])],
            ["GST", inr(q["tax_paise"])],
            ["Total (INR)", inr(q["total_paise"])],
        ],
        colWidths=[40 * mm, 34 * mm],
        hAlign="RIGHT",
    )
    totals.setStyle(TableStyle([
        ("FONT", (0, 0), (-1, -1), "Helvetica", 9),
        ("FONT", (0, 2), (-1, 2), "Helvetica-Bold", 10.5),
        ("ALIGN", (1, 0), (1, -1), "RIGHT"),
        ("LINEABOVE", (0, 2), (-1, 2), 0.8, INK),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
    ]))
    E.append(totals)

    if q.get("notes"):
        E.append(Paragraph("Notes", st["h2"]))
        E.append(Paragraph(clean(q["notes"]).replace("\n", "<br/>"), st["base"]))
    if q.get("terms"):
        E.append(Paragraph("Terms", st["h2"]))
        E.append(Paragraph(clean(q["terms"]).replace("\n", "<br/>"), st["small"]))
    E.append(Spacer(1, 12))
    if approved and q.get("approved_by"):
        E.append(Paragraph(f"Approved by {clean(q['approved_by']['full_name'])} on {_d(q.get('approved_at'))}.", st["small"]))
    elif not approved:
        E.append(Paragraph("<font color='#b45309'><b>Draft.</b></font> Not valid until approved by an authorised person.", st["small"]))

    decorate = _page_decorator(org.get("name", ""), label, None if approved else "DRAFT - NOT VALID", tz)
    doc.build(E, onFirstPage=decorate, onLaterPages=decorate)
    return buf.getvalue()
