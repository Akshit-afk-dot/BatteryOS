INK = colors.HexColor("#18181b")
MUTED = colors.HexColor("#71717a")
LINE = colors.HexColor("#e4e4e7")
SOFT = colors.HexColor("#f4f4f5")
ACCENT = colors.HexColor("#047857")
WARN = colors.HexColor("#b45309")

# The built-in PDF fonts cover WinAnsi only; map the few symbols we use.
_REPLACEMENTS = {"Ω": "Ohm", "₹": "INR ", "≥": ">=", "≤": "<=", "→": "->", "…": "...", " ": " ", "✓": "OK", "−": "-"}


def plain(text: Any) -> str:
    """Text safe for the built-in fonts (for canvas drawing, no markup)."""
    s = "" if text is None else str(text)
    for a, b in _REPLACEMENTS.items():
        s = s.replace(a, b)
    return s.encode("cp1252", "replace").decode("cp1252")


def clean(text: Any) -> str:
    """Text safe for the built-in fonts and escaped for Paragraph markup."""
    return escape(plain(text))


def _styles():
    ss = getSampleStyleSheet()
    base = ParagraphStyle("base", parent=ss["Normal"], fontName="Helvetica", fontSize=9, leading=12.5, textColor=INK)
    return {
        "base": base,
        "small": ParagraphStyle("small", parent=base, fontSize=7.5, leading=10, textColor=MUTED),
        "h1": ParagraphStyle("h1", parent=base, fontName="Helvetica-Bold", fontSize=16, leading=20, spaceAfter=2),
        "h2": ParagraphStyle("h2", parent=base, fontName="Helvetica-Bold", fontSize=11, leading=14, spaceBefore=10, spaceAfter=4),
        "label": ParagraphStyle("label", parent=base, fontSize=7.5, leading=10, textColor=MUTED),
        "cell": ParagraphStyle("cell", parent=base, fontSize=8, leading=10.5),
        "cellb": ParagraphStyle("cellb", parent=base, fontName="Helvetica-Bold", fontSize=8, leading=10.5),
        "right": ParagraphStyle("right", parent=base, alignment=TA_RIGHT),
        "origin": ParagraphStyle("origin", parent=base, fontSize=7.5, leading=10, textColor=ACCENT),
    }


def _table(rows: list[list[Any]], widths: list[float], header: bool = True, zebra: bool = True) -> Table:
    t = Table(rows, colWidths=widths, repeatRows=1 if header else 0)
    style = [
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ("LINEBELOW", (0, 0), (-1, -1), 0.4, LINE),
    ]
    if header:
        style += [("BACKGROUND", (0, 0), (-1, 0), SOFT), ("LINEBELOW", (0, 0), (-1, 0), 0.8, MUTED)]
    if zebra:
        for r in range(1 if header else 0, len(rows)):
            if r % 2 == 0:
                style.append(("BACKGROUND", (0, r), (-1, r), colors.HexColor("#fafafa")))
    t.setStyle(TableStyle(style))
    return t


def _page_decorator(org_name: str, doc_label: str, watermark: str | None, tz: str | None):
    now = timeutil.local(datetime.now(timezone.utc), tz)
    generated = now.strftime("%d %b %Y %H:%M ") + (now.tzname() or "")

    def draw(canvas, doc):
        canvas.saveState()
        w, h = A4
        canvas.setFont("Helvetica-Bold", 8)
        canvas.setFillColor(INK)
        canvas.drawString(18 * mm, h - 12 * mm, plain(org_name))
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(MUTED)
        canvas.drawRightString(w - 18 * mm, h - 12 * mm, plain(doc_label))
        canvas.setStrokeColor(LINE)
        canvas.line(18 * mm, h - 14 * mm, w - 18 * mm, h - 14 * mm)
        canvas.drawString(18 * mm, 10 * mm, f"Generated by BatteryOS on {generated}")
        canvas.drawRightString(w - 18 * mm, 10 * mm, f"Page {doc.page}")
        if watermark:
            canvas.setFont("Helvetica-Bold", 46)
            canvas.setFillColor(colors.Color(0.85, 0.2, 0.2, alpha=0.12))
            canvas.translate(w / 2, h / 2)
            canvas.rotate(35)
            canvas.drawCentredString(0, 0, watermark)
        canvas.restoreState()

    return draw


def _doc(buf: io.BytesIO, title: str) -> SimpleDocTemplate:
    return SimpleDocTemplate(
        buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=20 * mm, bottomMargin=18 * mm,
        title=title, author="BatteryOS",
    )


def _fmt_date(v: Any, tz: str | None = None) -> str:
    if v is None:
        return "—"
    if isinstance(v, datetime):
        return timeutil.local(v, tz).strftime("%d %b %Y")
    if isinstance(v, date):
        return v.strftime("%d %b %Y")
    if isinstance(v, str) and len(v) >= 10 and v[4] == "-" and v[7] == "-":
        try:
            return datetime.fromisoformat(v[:10]).strftime("%d %b %Y")
        except ValueError:
            return v
    return str(v)


def _num(v: Any, unit: str | None = None) -> str:
    if v is None:
        return "Unknown"
    s = f"{v:g}" if isinstance(v, float) else str(v)
    return f"{s} {unit}".strip() if unit else s


