"""Generate SYNTHETIC sample CSV files for trying out and testing the importer.

These files are produced by a simple mathematical model. They are NOT
measurements from any real battery and must never be presented as such. Their
only purpose is to exercise the CSV preview, validation and import workflow.

Usage:  python scripts/generate_samples.py   (writes into ./samples)
"""

from __future__ import annotations

import math
import random
from datetime import datetime, timedelta
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "samples"


def lfp_cell_ocv(soc: float) -> float:
    """Rough LFP open-circuit-voltage shape (synthetic)."""
    soc = min(max(soc, 0.0), 1.0)
    return 2.9 + 0.35 * (1 - math.exp(-soc * 12)) + 0.08 * soc + 0.25 * max(0.0, soc - 0.97) * 30


def clean_capacity_test() -> str:
    """CC discharge of a synthetic 16S 30 Ah LFP pack at 15 A, 10 s sampling."""
    rng = random.Random(42)
    capacity_ah = 27.6  # synthetic "true" capacity used to shape the curve
    lines = ["Test Time(s),Step,Voltage(V),Current(A),Temperature(C),Capacity(Ah)"]
    t, q = 0, 0.0
    # 5 minutes rest
    while t < 300:
        lines.append(f"{t},Rest,{16 * lfp_cell_ocv(1.0):.3f},0.000,{25.0 + rng.uniform(-0.1, 0.1):.1f},0.000")
        t += 10
    temp = 25.0
    while True:
        soc = 1 - q / capacity_ah
        v = 16 * (lfp_cell_ocv(soc) - 15 * 0.0009)
        if soc < 0.08:
            v -= (0.08 - soc) * 40
        if v <= 40.0:
            break
        temp += 0.004 + rng.uniform(-0.002, 0.003)
        lines.append(f"{t},CC Discharge,{v + rng.uniform(-0.01, 0.01):.3f},-15.000,{temp:.1f},{q:.3f}")
        t += 10
        q += 15 * 10 / 3600
    for _ in range(30):
        lines.append(f"{t},Rest,{16 * lfp_cell_ocv(0.02):.3f},0.000,{temp:.1f},{q:.3f}")
        t += 10
        temp -= 0.02
    return "\n".join(lines) + "\n"


def bms_export_with_issues() -> str:
    """Semicolon-separated, decimal-comma BMS log with deliberate data problems:
    metadata lines above the header, ambiguous dd/mm dates, a missing cell
    reading, a non-numeric value, a logging gap, a clock step backwards, a high
    temperature reading and one weak cell."""
    rng = random.Random(7)
    pre = [
        "# SYNTHETIC DEMO DATA - generated by scripts/generate_samples.py - not a real battery",
        "Device;DemoBMS (fictional)",
        "Export;Log export",
        "",
    ]
    cells = ";".join(f"Cell{i}(mV)" for i in range(1, 17))
    header = f"Date Time;Total Voltage (mV);Current;Temp1;Temp2;SOC;{cells}"
    rows = []
    start = datetime(2026, 3, 4, 9, 0, 0)
    soc = 0.92
    n = 720
    for k in range(n):
        ts = start + timedelta(seconds=30 * k)
        if k > 400:
            ts += timedelta(minutes=25)  # logging gap
        if k == 600:
            ts -= timedelta(minutes=3)  # clock steps back
        current = -6.0 if 60 <= k < 520 else 0.0
        soc -= (-current) * 30 / 3600 / 30
        cell_v = []
        for c in range(16):
            base = lfp_cell_ocv(soc) + current * 0.0008
            if c == 6:
                base -= 0.035 + (0.92 - soc) * 0.08  # weak cell
            cell_v.append(base + rng.uniform(-0.002, 0.002))
        pack_mv = sum(cell_v) * 1000
        t1 = 27.0 + (k / n) * 6 + rng.uniform(-0.2, 0.2)
        t2 = t1 + 1.1
        if k == 500:
            t2 = 63.4  # high reading
        cell_txt = ";".join(f"{v * 1000:.0f}" for v in cell_v)
        if k == 250:
            cell_txt = ";".join(["" if i == 9 else f"{v * 1000:.0f}" for i, v in enumerate(cell_v)])
        temp1 = "ERR" if k == 333 else f"{t1:.1f}".replace(".", ",")
        rows.append(
            f"{ts.strftime('%d/%m/%Y %H:%M:%S')};{pack_mv:.0f};{current:.2f}".replace(".", ",")
            + f";{temp1};{f'{t2:.1f}'.replace('.', ',')};{soc * 100:.1f}".replace(".", ",")
            + f";{cell_txt}"
        )
    return "\n".join(pre + [header] + rows) + "\n"


def summary_only() -> str:
    """A file with no time column — should be rejected with a clear error."""
    return "Cell,Voltage (V),IR (mOhm)\n" + "\n".join(
        f"{i},{3.28 + i * 0.001:.3f},{0.42 + i * 0.01:.2f}" for i in range(1, 17)
    ) + "\n"


def main() -> None:
    OUT.mkdir(exist_ok=True)
    files = {
        "SYNTHETIC_capacity_test_16S_LFP_clean.csv": clean_capacity_test(),
        "SYNTHETIC_bms_export_with_issues.csv": bms_export_with_issues(),
        "SYNTHETIC_cell_summary_no_time_column.csv": summary_only(),
    }
    for name, text in files.items():
        (OUT / name).write_text(text, encoding="utf-8", newline="")
        print(f"wrote samples/{name} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
