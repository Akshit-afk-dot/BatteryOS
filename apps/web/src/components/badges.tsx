import { Badge, type Tone } from "@/components/ui";
import { Tooltip } from "@/components/overlay";
import { KIND_LABELS, PROVENANCE_LABELS, QUOTE_STATUS_LABELS, ROLE_LABELS, STATUS_LABELS, label } from "@/lib/format";

export const STATUS_TONES: Record<string, Tone> = {
  received: "slate",
  awaiting_data: "amber",
  testing: "sky",
  review_required: "violet",
  quoted: "indigo",
  approved: "teal",
  repair_in_progress: "orange",
  ready: "emerald",
  dispatched: "dark",
  rejected: "rose",
  archived: "zinc",
};

export const STATUS_BAR: Record<string, string> = {
  received: "bg-slate-400",
  awaiting_data: "bg-amber-400",
  testing: "bg-sky-500",
  review_required: "bg-violet-500",
  quoted: "bg-indigo-500",
  approved: "bg-teal-500",
  repair_in_progress: "bg-orange-500",
  ready: "bg-emerald-500",
  dispatched: "bg-zinc-700",
  rejected: "bg-rose-500",
  archived: "bg-zinc-300",
};

export function StatusBadge({ status, className }: { status: string; className?: string }) {
  return (
    <Badge tone={STATUS_TONES[status] ?? "zinc"} dot className={className}>
      {label(STATUS_LABELS, status)}
    </Badge>
  );
}

const KIND_META: Record<string, { tone: Tone; icon: React.ReactNode; hint: string }> = {
  measured: { tone: "sky", icon: <Gauge />, hint: "Recorded from a test session, with its conditions." },
  user_entered: { tone: "zinc", icon: <PenLine />, hint: "Typed in by staff; not independently measured." },
  calculated: { tone: "violet", icon: <Calculator />, hint: "Computed by BatteryOS from imported data. The method is shown with the value." },
  external: { tone: "cyan", icon: <FileCheck2 />, hint: "A result from another lab, report or document." },
  model_estimate: { tone: "amber", icon: <FlaskConical />, hint: "An estimate from a named, validated model. Not a measurement." },
  technician: { tone: "emerald", icon: <Wrench />, hint: "A technician's observation." },
  system: { tone: "slate", icon: <BadgeCheck />, hint: "Generated by BatteryOS from the record (e.g. completeness check)." },
};

export function KindBadge({ kind, compact }: { kind: string; compact?: boolean }) {
  const meta = KIND_META[kind] ?? KIND_META.user_entered;
  return (
    <Tooltip content={meta.hint}>
      <span>
        <Badge tone={meta.tone}>
          {meta.icon}
          {compact ? null : label(KIND_LABELS, kind)}
        </Badge>
      </span>
    </Tooltip>
  );
}

const PROV_TONES: Record<string, Tone> = {
  nameplate: "emerald",
  datasheet: "emerald",
  bms_reported: "sky",
  technician_verified: "emerald",
  customer_reported: "amber",
  unverified: "zinc",
  unknown: "zinc",
};

export function ProvenanceBadge({ source }: { source: string }) {
  return (
    <Badge tone={PROV_TONES[source] ?? "zinc"} className={source === "unknown" ? "text-zinc-500" : undefined}>
      {source === "unknown" ? <ShieldQuestion /> : null}
      {label(PROVENANCE_LABELS, source)}
    </Badge>
  );
}

const ORIGIN_META: Record<string, { tone: Tone; icon: React.ReactNode; text: string; hint: string }> = {
  ai: { tone: "fuchsia", icon: <Sparkles />, text: "AI draft", hint: "Drafted by the AI assistant from the selected evidence. Needs human review." },
  ai_edited: { tone: "fuchsia", icon: <UserPen />, text: "AI draft · edited", hint: "Drafted by AI, then edited by a person." },
  template: { tone: "zinc", icon: <LayoutTemplate />, text: "Template", hint: "Generated from the records by a fixed template (no AI)." },
  template_edited: { tone: "zinc", icon: <UserPen />, text: "Template · edited", hint: "Template text edited by a person." },
  human: { tone: "emerald", icon: <PenLine />, text: "Written by reviewer", hint: "Written by a person." },
};

export function OriginBadge({ origin }: { origin: string }) {
  const m = ORIGIN_META[origin] ?? ORIGIN_META.human;
  return (
    <Tooltip content={m.hint}>
      <span>
        <Badge tone={m.tone}>
          {m.icon}
          {m.text}
        </Badge>
      </span>
    </Tooltip>
  );
}

export function GeneratorBadge({ generator }: { generator: string }) {
  if (generator.startsWith("anthropic:")) {
    return (
      <Tooltip content={`Narrative drafted with ${generator.split(":")[1]} from the selected evidence only.`}>
        <span>
          <Badge tone="fuchsia">
            <Sparkles />
            AI-assisted draft
          </Badge>
        </span>
      </Tooltip>
    );
  }
  if (generator === "template") {
    return (
      <Badge tone="zinc">
        <LayoutTemplate />
        Template draft
      </Badge>
    );
  }
  return (
    <Badge tone="emerald">
      <Bot />
      {generator}
    </Badge>
  );
}

const QUOTE_TONES: Record<string, Tone> = {
  draft: "zinc",
  approved: "teal",
  sent: "sky",
  accepted: "emerald",
  declined: "rose",
  void: "zinc",
};

export function QuoteStatusBadge({ status }: { status: string }) {
  return (
    <Badge tone={QUOTE_TONES[status] ?? "zinc"} dot className={status === "void" ? "line-through" : undefined}>
      {label(QUOTE_STATUS_LABELS, status)}
    </Badge>
  );
}

export function ReportStatusBadge({ status }: { status: string }) {
  const tone: Tone = status === "approved" ? "emerald" : status === "superseded" ? "zinc" : "amber";
  return (
    <Badge tone={tone} dot>
      {status === "draft" ? "Draft — not approved" : status === "approved" ? "Approved" : "Superseded"}
    </Badge>
  );
}

export function RoleBadge({ role }: { role: string }) {
  const tone: Tone = role === "owner" ? "dark" : role === "admin" ? "indigo" : role === "technician" ? "teal" : "zinc";
  return <Badge tone={tone}>{label(ROLE_LABELS, role)}</Badge>;
}

export function SeverityBadge({ severity }: { severity: "error" | "warning" | "info" }) {
  const tone: Tone = severity === "error" ? "rose" : severity === "warning" ? "amber" : "sky";
  return <Badge tone={tone}>{severity === "error" ? "Error" : severity === "warning" ? "Warning" : "Info"}</Badge>;
}
